// orchestrate.js — The main refresh runner for the Living Book v2.
//
// Refreshes the answer for ONE question at a time. It fetches a fresh
// answer (either a deterministic mock, or — in live mode — from the
// Abacus.AI API), records it as a new claim, bumps the question's edition,
// appends an immutable ledger entry, and logs every action.
//
// Usage:
//   node scripts/orchestrate.js --question-id q001 --mock   # safe, offline
//   node scripts/orchestrate.js --question-id q001          # live (needs key)
//
// Live mode reads the API key from process.env.ABACUS_API_KEY ONLY.
// No credential is ever written to disk or hardcoded here.

const fs = require("fs");
const path = require("path");
const {
  PATHS,
  readJSON,
  writeJSON,
  today,
  nowISO,
  classifySource,
  summarise,
} = require("./lib.js");
const { parseArgs } = require("./propose-question.js");
const { runEnsemble } = require("./agents/ensemble.js");

// ── Logging ─────────────────────────────────────────────────────────
function log(message) {
  fs.mkdirSync(path.dirname(PATHS.orchestrationLog), { recursive: true });
  const line = `${nowISO()}  ${message}\n`;
  fs.appendFileSync(PATHS.orchestrationLog, line);
  return line;
}

// ── Fresh-answer providers ──────────────────────────────────────────
// MOCK: deterministic, offline, no network. Used by tests and dry-runs.
function mockAnswer(questionId, questionText) {
  return {
    text:
      `**[MOCK REFRESH]** This is a deterministic mock answer for ` +
      `${questionId}. In live mode this text would be generated by the ` +
      `Abacus.AI model in response to the question: "${questionText}". ` +
      `No network call was made.`,
    sources: [
      {
        title: "Mock source (orchestrator self-test)",
        url: "https://example.com/mock/" + questionId,
      },
    ],
    model: "mock",
  };
}

// LIVE: call the Abacus.AI API. Isolated so it is never exercised by tests.
async function liveAnswer(questionText) {
  const apiKey = process.env.ABACUS_API_KEY;
  if (!apiKey) {
    throw new Error(
      "ABACUS_API_KEY is not set. Provide it via the environment, " +
        "or run with --mock for an offline refresh."
    );
  }

  // Abacus.AI ChatLLM / RouteLLM completion endpoint. The exact model and
  // routing are configured server-side against the provided key.
  const endpoint =
    process.env.ABACUS_API_ENDPOINT ||
    "https://api.abacus.ai/api/v0/getChatResponse";

  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      "apiKey": apiKey,
      "content-type": "application/json",
    },
    body: JSON.stringify({
      messages: [
        {
          is_user: true,
          text:
            "Provide an up-to-date, well-sourced answer to the following " +
            "question about AI in education. Cite sources with URLs.\n\n" +
            questionText,
        },
      ],
    }),
  });

  if (!response.ok) {
    throw new Error(
      `Abacus.AI API error ${response.status}: ${await response.text()}`
    );
  }

  const data = await response.json();
  // Defensive extraction: the response envelope may vary by deployment.
  const text =
    data?.result?.messages?.slice(-1)[0]?.text ||
    data?.result?.answer ||
    data?.answer ||
    (typeof data === "string" ? data : JSON.stringify(data));

  const rawSources =
    data?.result?.search_results || data?.result?.sources || [];
  const sources = rawSources
    .filter((s) => s && (s.url || s.link))
    .map((s) => ({ title: s.title || s.url || s.link, url: s.url || s.link }));

  return { text: String(text).trim(), sources, model: "abacus.ai" };
}

// ── Core refresh logic ──────────────────────────────────────────────
// Exported and testable. `provider` lets tests inject a fake fetcher.
async function orchestrate(
  questionId,
  {
    mock = false,
    provider = null,
    persist = true,
    ensemble = false,
    apiCall = null,
  } = {}
) {
  if (!questionId || !/^q\d+$/.test(questionId)) {
    throw new Error(`Invalid --question-id "${questionId}" (expected qNNN).`);
  }

  const mode = `${mock ? "mock" : "live"}${ensemble ? "+ensemble" : ""}`;
  log(`START refresh ${questionId} (mode=${mode})`);

  // 1. Confirm the question exists and is active in the registry.
  const registry = readJSON(PATHS.registry, null);
  if (!registry) {
    throw new Error(
      "Registry not found. Run `node scripts/migrate.js` first."
    );
  }
  const regEntry = registry.questions.find((q) => q.id === questionId);
  if (!regEntry) {
    log(`ABORT ${questionId}: not found in registry`);
    throw new Error(`Question ${questionId} is not in the registry.`);
  }
  if (regEntry.status === "deprecated") {
    log(`ABORT ${questionId}: deprecated`);
    throw new Error(`Question ${questionId} is deprecated; refusing to refresh.`);
  }

  // 2. Determine the next global edition number from the ledger.
  const ledger = readJSON(PATHS.ledger, { editions: [] });
  const maxEdition = ledger.editions.reduce(
    (m, e) => Math.max(m, e.edition_number || 0),
    0
  );
  const newEdition = maxEdition + 1;

  const claimFilePath = path.join(PATHS.claimsDir, `${questionId}.json`);
  const existing = readJSON(claimFilePath, null);
  const day = today();

  const claimFile = existing || {
    question_id: questionId,
    question_text: regEntry.question,
    current_edition: 0,
    claims: [],
    answer_summary: "",
    disputed_aspects: [],
  };

  let newClaims;

  if (ensemble) {
    // ── Multi-agent path: Research → Verification → Synthesis ────────
    const result = await runEnsemble({
      questionId,
      mock,
      edition: newEdition,
      apiCall,
      registryData: registry,
    });
    const synthesized = result.claimFile;
    if (!synthesized.claims.length) {
      log(`FAIL ${questionId}: ensemble produced no verified claims`);
      throw new Error("Ensemble produced no verified claims.");
    }
    // Renumber synthesized claims to continue after existing ones so ids
    // never collide within the claim file.
    const offset = claimFile.claims.length;
    newClaims = synthesized.claims.map((c, i) => ({
      ...c,
      claim_id: `${questionId}-c${String(offset + i + 1).padStart(2, "0")}`,
    }));
    claimFile.claims.push(...newClaims);
    claimFile.answer_summary = synthesized.answer_summary;
    // Merge disputed aspects (dedupe by source_url).
    const seen = new Set(
      (claimFile.disputed_aspects || []).map((d) => d.source_url)
    );
    for (const d of synthesized.disputed_aspects) {
      if (!seen.has(d.source_url)) {
        claimFile.disputed_aspects.push(d);
        seen.add(d.source_url);
      }
    }
    log(
      `FETCHED ${questionId} via ensemble: ${newClaims.length} claim(s), ` +
        `${synthesized.disputed_aspects.length} disputed`
    );
  } else {
    // ── Single-shot path (default, unchanged) ────────────────────────
    let fresh;
    if (provider) {
      fresh = await provider(questionId, regEntry.question);
    } else if (mock) {
      fresh = mockAnswer(questionId, regEntry.question);
    } else {
      fresh = await liveAnswer(regEntry.question);
    }
    if (!fresh || !fresh.text) {
      log(`FAIL ${questionId}: provider returned no text`);
      throw new Error("Answer provider returned no text.");
    }
    log(
      `FETCHED ${questionId}: ${fresh.text.length} chars, ` +
        `${(fresh.sources || []).length} source(s) via ${fresh.model || "?"}`
    );

    const sources = (fresh.sources || []).map((s) => {
      const { type, credibility } = classifySource(s.url);
      return {
        url: s.url,
        title: s.title || s.url,
        type,
        retrieved: day,
        credibility,
      };
    });

    const nextClaimNum = claimFile.claims.length + 1;
    const newClaim = {
      claim_id: `${questionId}-c${String(nextClaimNum).padStart(2, "0")}`,
      text: fresh.text,
      reliability: "established",
      sources,
      perspectives: [],
      last_verified: day,
      added_edition: newEdition,
    };
    claimFile.claims.push(newClaim);
    claimFile.answer_summary = summarise(fresh.text);
    newClaims = [newClaim];
  }

  claimFile.current_edition = newEdition;
  claimFile.question_text = regEntry.question;

  // 5. Append the immutable ledger entry.
  const wasNew = !existing;
  const authorBase = ensemble ? "ensemble" : "orchestrator";
  ledger.editions.push({
    edition_number: newEdition,
    created_at: nowISO(),
    description: `Refreshed ${questionId} via ${mock ? "mock " : ""}${authorBase}.`,
    questions_updated: wasNew ? [] : [questionId],
    questions_added: wasNew ? [questionId] : [],
    questions_deprecated: [],
    author: mock ? `${authorBase}(mock)` : authorBase,
  });

  // 6. If this question was only "proposed", promote it to active.
  if (regEntry.status === "proposed") {
    regEntry.status = "active";
    if (regEntry.added_in_edition == null) regEntry.added_in_edition = newEdition;
  }

  if (persist) {
    writeJSON(claimFilePath, claimFile);
    writeJSON(PATHS.ledger, ledger);
    writeJSON(PATHS.registry, registry);
  }

  const primaryClaim = newClaims[newClaims.length - 1];
  log(`DONE ${questionId}: wrote edition ${newEdition}, ` +
      `${newClaims.length} claim(s), last ${primaryClaim.claim_id}`);

  return {
    questionId,
    edition: newEdition,
    claim: primaryClaim,
    claims: newClaims,
    claimFile,
    ledger,
  };
}

// ── CLI entry point ─────────────────────────────────────────────────
if (require.main === module) {
  const args = parseArgs(process.argv.slice(2));
  const questionId = args["question-id"];
  const mock = Boolean(args.mock);
  const ensemble = Boolean(args.ensemble);

  orchestrate(questionId, { mock, ensemble })
    .then((r) => {
      console.log(`✓ Refreshed ${r.questionId}`);
      console.log(`  edition : ${r.edition}`);
      console.log(`  claims  : ${r.claims.length} (last ${r.claim.claim_id})`);
      console.log(`  sources : ${r.claim.sources.length}`);
      console.log(`  log     : ${path.relative(PATHS.root, PATHS.orchestrationLog)}`);
    })
    .catch((err) => {
      console.error("✗ Orchestration failed: " + err.message);
      process.exit(1);
    });
}

module.exports = { orchestrate, mockAnswer };
